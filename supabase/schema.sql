-- 1. Create Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    password_salt VARCHAR(64) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    otp_code VARCHAR(6) DEFAULT NULL,
    otp_expires_at TIMESTAMPTZ DEFAULT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Index for fast user authentication lookups
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users (email);
CREATE INDEX IF NOT EXISTS idx_users_created_at ON public.users (created_at DESC);

-- 2. Create Disaster Recovery Backup History Table
CREATE TABLE IF NOT EXISTS public.infosec_backup_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation VARCHAR(16) NOT NULL CHECK (operation IN ('backup', 'restore')),
    drive_file_id VARCHAR(255) DEFAULT NULL,
    file_name VARCHAR(255) DEFAULT NULL,
    size_bytes BIGINT DEFAULT NULL,
    sha256 CHAR(64) DEFAULT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('success', 'failed', 'expired')),
    message VARCHAR(500) DEFAULT NULL,
    requested_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ DEFAULT NULL,
    snapshot_data TEXT DEFAULT NULL
);

-- Indexes for backup history
CREATE INDEX IF NOT EXISTS idx_backup_started_at ON public.infosec_backup_history (started_at DESC);
CREATE INDEX IF NOT EXISTS idx_backup_operation_status ON public.infosec_backup_history (operation, status);

-- 3. Row Level Security (RLS) Configuration
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.infosec_backup_history ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if re-running
DROP POLICY IF EXISTS "Allow anon read users" ON public.users;
DROP POLICY IF EXISTS "Allow anon insert users" ON public.users;
DROP POLICY IF EXISTS "Allow anon update users" ON public.users;
DROP POLICY IF EXISTS "Allow anon read backup history" ON public.infosec_backup_history;
DROP POLICY IF EXISTS "Allow anon insert backup history" ON public.infosec_backup_history;
DROP POLICY IF EXISTS "Allow anon update backup history" ON public.infosec_backup_history;

-- RLS Policies for Application Access via Supabase Anon Key:
CREATE POLICY "Allow anon read users"
    ON public.users
    FOR SELECT
    TO anon, authenticated
    USING (true);

CREATE POLICY "Allow anon insert users"
    ON public.users
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

CREATE POLICY "Allow anon update users"
    ON public.users
    FOR UPDATE
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow anon read backup history"
    ON public.infosec_backup_history
    FOR SELECT
    TO anon, authenticated
    USING (true);

CREATE POLICY "Allow anon insert backup history"
    ON public.infosec_backup_history
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

CREATE POLICY "Allow anon update backup history"
    ON public.infosec_backup_history
    FOR UPDATE
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

